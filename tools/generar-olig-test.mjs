import fs from "node:fs";
import path from "node:path";
import assert from "node:assert";
import { fileURLToPath } from "node:url";
const RAIZ = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const img = fs.readFileSync(path.join(RAIZ, "contratos-olig", "logo", "test-200.webp"));
assert.ok(img.slice(0, 4).toString() === "RIFF" && img.slice(8, 12).toString() === "WEBP", "no es una webp");
const logo = "data:image/webp;base64," + img.toString("base64");
const descripcion = "Test token: the same contract as Oligarc, with a test name, picture and links.";
const json = JSON.stringify({ name: "TEST", symbol: "TEST", description: descripcion, image: logo, website: "https://example.com/", twitter: "https://x.com/x", telegram: "https://t.me/telegram" });
const tokenURI = "data:application/json;base64," + Buffer.from(json, "utf8").toString("base64");
assert.ok(!/["\\]/.test(logo + tokenURI + descripcion), "nada que escapar en Solidity");
const sol = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.37;

import {ERC20} from "@openzeppelin/contracts/token/ERC20/ERC20.sol";
import {ERC20Burnable} from "@openzeppelin/contracts/token/ERC20/extensions/ERC20Burnable.sol";
import {ERC20Permit} from "@openzeppelin/contracts/token/ERC20/extensions/ERC20Permit.sol";

/// @title TEST (a test copy of Oligarc)
/// @notice The same contract as Oligarc ($OLIG), with a test name, picture and links, to check what trackers show before the
///         real one. 1,000,000,000 TEST minted once to the deployer. No owner, no admin, no mint, no pause, no tax.
/// @dev GENERATED by tools/generar-olig-test.mjs (the picture is contratos-olig/logo/test-200.webp). Do not edit by hand.
contract OligTest is ERC20, ERC20Burnable, ERC20Permit {
    uint256 public constant INITIAL_SUPPLY = 1_000_000_000 ether;

    string public constant tokenURI = "${tokenURI}";
    string public constant logo = "${logo}";
    string public constant description = "${descripcion}";

    address public constant owner = address(0);

    constructor() ERC20("TEST", "TEST") ERC20Permit("TEST") {
        _mint(msg.sender, INITIAL_SUPPLY);
    }
}
`;
fs.writeFileSync(path.join(RAIZ, "contratos-olig", "src", "OligTest.sol"), sol);
