import fs from "node:fs";
import path from "node:path";
import assert from "node:assert";
import { fileURLToPath } from "node:url";
const RAIZ = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOGO = path.join(RAIZ, "contratos-olig", "logo", "olig-200.webp");
const img = fs.readFileSync(LOGO);
assert.ok(img.slice(0, 4).toString() === "RIFF" && img.slice(8, 12).toString() === "WEBP", "no es una webp");
const logo = "data:image/webp;base64," + img.toString("base64");
const descripcion = "The OligArc token. Every whale. Every position. Live.";
// el mismo orden de claves que el TEST de basey que GMGN pinto (name, symbol, ..., image, website, twitter); sin telegram (no hay)
const json = JSON.stringify({ name: "Oligarc", symbol: "OLIG", description: descripcion, image: logo, website: "https://oligarc.xyz", twitter: "https://x.com/oligarcxyz" });
const tokenURI = "data:application/json;base64," + Buffer.from(json, "utf8").toString("base64");
assert.ok(!/["\\]/.test(logo + tokenURI + descripcion), "nada que escapar en Solidity");
const sol = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.37;

import {ERC20} from "@openzeppelin/contracts/token/ERC20/ERC20.sol";
import {ERC20Burnable} from "@openzeppelin/contracts/token/ERC20/extensions/ERC20Burnable.sol";
import {ERC20Permit} from "@openzeppelin/contracts/token/ERC20/extensions/ERC20Permit.sol";

/// @title Oligarc ($OLIG)
/// @notice The Oligarc token. A fixed supply of 1,000,000,000 OLIG is minted once, at deployment, to the deployer.
///         There is no owner and no admin: nobody can mint more, pause, blacklist, tax or move anyone else's tokens.
///         Holders can burn their own tokens (burn / burnFrom), and approve with a signature (EIP-2612 permit).
///         Trading fees and burns for buys and sells will live in the trading pool's hook, never in this contract.
/// @dev GENERATED by tools/generar-olig-sol.mjs (the picture is contratos-olig/logo/olig-200.webp). Do not edit by hand.
contract Oligarc is ERC20, ERC20Burnable, ERC20Permit {
    /// @notice The supply minted at deployment: one billion tokens with 18 decimals.
    uint256 public constant INITIAL_SUPPLY = 1_000_000_000 ether;

    /// @notice Picture, description and links, in the getters the trackers on Arc read: tokenURI() is a JSON data URI
    ///         (name, symbol, description, image, website, twitter), logo() is the picture itself.
    ///         Everything lives inside the contract, so no host or gateway has to stay alive. Fixed at deployment:
    ///         nobody can change it later.
    string public constant tokenURI = "${tokenURI}";
    string public constant logo = "${logo}";
    string public constant description = "${descripcion}";

    /// @notice There is no owner and there never was: this token has no owner-only function at all. The getter exists
    ///         so anyone, and any tracker, can check it on chain instead of taking it on trust.
    address public constant owner = address(0);

    constructor() ERC20("Oligarc", "OLIG") ERC20Permit("Oligarc") {
        _mint(msg.sender, INITIAL_SUPPLY);
    }
}
`;
fs.writeFileSync(path.join(RAIZ, "contratos-olig", "src", "Oligarc.sol"), sol);
fs.writeFileSync(path.join(RAIZ, "contratos-olig", "logo", "esperado.json"), JSON.stringify({ tokenURI, logo, description: descripcion, json }, null, 1));
console.log("Oligarc.sol | logo", img.length, "bytes ->", logo.length, "caracteres | tokenURI", tokenURI.length, "caracteres | JSON sin imagen:",
  json.replace(/"image":"[^"]*"/, '"image":"data:…"'));
